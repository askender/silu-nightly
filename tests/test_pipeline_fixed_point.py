"""The pipeline-level fixed point: the self-hosted pipeline (native
front end + native converter + clang, Python only orchestrating) builds
its own compiler components, and the second-generation artifacts
reproduce the first generation byte-for-byte.

 - fe2, built by the pipeline from the front-end wrapper, emits IR
   identical to the bootstrap fe (probe: a benchmark and silu_fe.si)
 - conv2, built by the pipeline from the converter wrapper, converts
   its own IR (generated by fe2 - no Python front end anywhere in the
   chain) and must reproduce the .ll that built it, byte-for-byte;
   the previous-generation converter agrees on the same bytes
 - siluc2, the MONOLITH built by the pipeline, produces .ll identical
   to the split fe2|conv2 chain - one process, same bytes

Artifacts are cached under ~/.cache/silu-selfhost keyed by source
mtime, so repeat runs only re-run the conversion checks.
"""

import importlib.util
import os
import subprocess

import pytest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(os.path.expanduser("~"), ".cache", "silu-selfhost")

_spec = importlib.util.spec_from_file_location(
    "selfhost_build", os.path.join(REPO, "tools", "selfhost_build.py")
)
shb = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(shb)


def _run(cmd, **kw):
    kw.setdefault("cwd", REPO)
    return subprocess.run(cmd, capture_output=True, timeout=1800, **kw)


@pytest.fixture(scope="module")
def generations():
    if subprocess.run(["clang", "--version"], capture_output=True).returncode != 0:
        pytest.skip("clang not available")
    os.makedirs(CACHE, exist_ok=True)
    fe = shb.ensure_frontend()
    conv = shb.ensure_converter()

    fe2 = os.path.join(CACHE, "silu_fe2")
    if any(shb._newer(d, fe2) for d in shb.FE_DEPS):
        shb.compile_with(fe, conv, shb.FE_MAIN, fe2)

    conv2 = os.path.join(CACHE, "silu_conv2")
    conv2_ll = os.path.join(CACHE, "silu_conv2_build.ll")
    if any(shb._newer(d, conv2) for d in shb.CONV_DEPS[:3]):
        shb.compile_with(fe, conv, shb.CONV_MAIN, conv2, save_ll=conv2_ll)
    return fe, conv, fe2, conv2, conv2_ll


def test_fe2_emits_identical_ir(generations):
    """Second-generation front end == first generation on probes."""
    fe, _, fe2, _, _ = generations
    for probe in ("benchmarks/fib.si", "selfhost/silu_fe.si"):
        a = _run([fe], stdin=open(os.path.join(REPO, probe)))
        b = _run([fe2], stdin=open(os.path.join(REPO, probe)))
        assert a.returncode == 0 and b.returncode == 0, (probe, a.stderr, b.stderr)
        assert a.stdout == b.stdout, f"fe2 diverges from fe on {probe}"


def test_conv2_reproduces_its_own_ll(generations):
    """The heart of the gate: conv2 converting its own IR (the IR
    produced by fe2, also pipeline-born) reproduces the exact .ll that
    built conv2."""
    _, conv, _, conv2, conv2_ll = generations
    ir = _run(
        [os.path.join(CACHE, "silu_fe2")],
        stdin=open(shb.CONV_MAIN, "r"),
        cwd=os.path.dirname(shb.CONV_MAIN),
    )
    assert ir.returncode == 0, ir.stderr[:400]
    out = subprocess.run([conv2], input=ir.stdout, capture_output=True,
                         timeout=1800)
    assert out.returncode == 0, out.stderr[:400]
    with open(conv2_ll, "rb") as h:
        build_ll = h.read()
    assert out.stdout == build_ll, (
        "conv2 self-conversion diverged from its own build .ll"
    )
    # the previous generation agrees on the same bytes
    prev = subprocess.run([conv], input=ir.stdout, capture_output=True,
                          timeout=1800)
    assert prev.returncode == 0, prev.stderr[:400]
    assert prev.stdout == build_ll


def test_siluc_monolith_matches_split_chain():
    """The monolith (fe + converter import-inlined, ONE process) emits
    the same .ll as the split two-process chain - and as the Python
    reference plane."""
    # `siluc` is now the C DRIVER (file-in, binary-out); the stdin->
    # .ll monolith lives on as siluc1
    shb.ensure_siluc()  # stale siluc1 vs fresh fe2/conv2 once caused
    #                    # a phantom divergence here (mtime check only
    #                    # runs inside selfhost_build, not on raw use)
    siluc1 = shb.SILUC1_BIN
    fe2 = os.path.join(CACHE, "silu_fe2")
    conv2 = os.path.join(CACHE, "silu_conv2")
    if not (os.path.exists(fe2) and os.path.exists(conv2)):
        pytest.skip("generations fixture not run first")
    for probe in ("benchmarks/fib.si", "benchmarks/jsonparse.si"):
        path = os.path.join(REPO, probe)
        one = _run([siluc1], stdin=open(path))
        assert one.returncode == 0, one.stderr[:400]
        ir = _run([fe2], stdin=open(path))
        two = subprocess.run([conv2], input=ir.stdout, capture_output=True,
                             timeout=1800)
        assert two.returncode == 0, two.stderr[:400]
        assert one.stdout == two.stdout, f"siluc diverges from fe2|conv2 on {probe}"


def test_pipeline_binaries_run(generations):
    """The pipeline-built front end and converter actually work on a
    real program end to end."""
    _, _, fe2, conv2, _ = generations
    ir = _run([fe2], stdin=open(os.path.join(REPO, "benchmarks/fib.si")))
    assert ir.returncode == 0, ir.stderr[:200]
    r = subprocess.run([conv2], input=ir.stdout, capture_output=True)
    assert r.returncode == 0, r.stderr[:200]
    assert b"define" in r.stdout and len(r.stdout) > 10000
